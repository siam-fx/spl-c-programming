//Write a C program that demonstrates the use of single-line (//) and multi-line (/* */) comments.

#include <stdio.h>

int main() {
    // This is a single-line comment
    int num = 10;

    /*
       This is a multi-line comment.
       It can span across multiple lines.
    */

    printf("The number is: %d\n", num); // Displaying the value of num

    return 0;
}
