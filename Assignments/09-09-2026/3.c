// Write a C program to demonstrate the use of increment and decrement operators. 

#include <stdio.h>

int main(){
    
    int x = 10;

    printf("%d\n" , x++);
    printf("%d\n" , ++x);
    printf("%d\n" , x--);
    printf("%d\n" , --x);
    printf("%d\n" , x);
    printf("%d\n" , x++);
    printf("%d\n" , x--);
    printf("%d\n" , ++x);
    printf("%d\n" , x++);

    return 0;
}